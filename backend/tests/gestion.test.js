test('validación monetaria exacta y fechas reales',()=>{
  for(const n of [0,-1,'NaN','1e3','0.001',true,null,'10000000000','Infinity',''])assert.throws(()=>monto(n));
  assert.equal(monto('123.45'),'123.45');assert.equal(monto(1),'1.00');
  for(const d of ['2026-02-30','2026-13-01','hoy'])assert.throws(()=>fecha(d));
  assert.equal(fecha('2028-02-29'),'2028-02-29');
});

test('mensualidades: meses vencidos, exentos, pagados, tarifas y adelantos',()=>{
  assert.equal(sumarMeses('2026-11',3),'2027-02');assert.equal(sumarMeses('2026-01',-1),'2025-12');
  assert.equal(nombrePeriodo('2026-09'),'septiembre 2026');
  const tarifas=[{desde:'2026-06',monto:'20.00',dia_vencimiento:10},{desde:'2026-09',monto:'25.00',dia_vencimiento:10}];
  const base={voluntario:{created_at:new Date('2026-01-15T12:00:00Z'),inicio:null},tarifas,hoy:'2026-10-21'};
  const e=calcularEstado({...base,pagos:[{periodo:'2026-06',monto:'20.00',comprobante:'FIN009'}],exenciones:[{desde:'2026-07',hasta:'2026-07',motivo:'Licencia'}]});
  assert.equal(e.inicio,'2026-06');
  assert.deepEqual(e.meses.filter(m=>m.periodo<='2026-10').map(m=>m.estado),['pagado','exento','vencido','vencido','vencido']);
  assert.equal(e.deuda,70);assert.equal(e.meses_vencidos,3);assert.equal(e.estado,'debe');
  assert.deepEqual(e.por_cobrar.slice(0,3).map(m=>m.periodo),['2026-08','2026-09','2026-10']);
  assert.equal(e.por_cobrar.length,3+11);assert.equal(e.por_cobrar.at(-1).estado,'adelanto');
  // Antes del día de vencimiento, el mes en curso está pendiente pero el voluntario sigue al día.
  const alDia=calcularEstado({...base,voluntario:{...base.voluntario,inicio:'2026-10'},pagos:[],exenciones:[],hoy:'2026-10-05'});
  assert.equal(alDia.estado,'al_dia');assert.equal(alDia.mes_actual.estado,'pendiente');
  assert.equal(calcularEstado({...base,tarifas:[],pagos:[],exenciones:[]}).meses.length,0);
});

